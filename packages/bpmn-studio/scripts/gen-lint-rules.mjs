// Generates src/server/lint-rules.gen.ts: a static bpmnlint rule/config cache so the
// bundled server needs no node_modules at runtime (plugin installs ship only dist/).
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const out = path.join(root, "src/server/lint-rules.gen.ts");

const bpmnlintDir = path.dirname(require.resolve("bpmnlint/package.json"));
const compatDir = path.dirname(require.resolve("bpmnlint-plugin-camunda-compat/package.json"));
const compat = require("bpmnlint-plugin-camunda-compat");

const lines = ["// GENERATED by scripts/gen-lint-rules.mjs — do not edit", "/* eslint-disable */", "// @ts-nocheck"];
const entries = [];
let n = 0;
const imp = (spec) => {
  const id = `r${n++}`;
  lines.push(`import ${id} from ${JSON.stringify(spec)};`);
  return id;
};

for (const f of fs.readdirSync(path.join(bpmnlintDir, "rules"))) {
  if (!f.endsWith(".js")) continue;
  const name = f.replace(/\.js$/, "");
  entries.push([`rule:bpmnlint/${name}`, imp(`bpmnlint/rules/${name}`)]);
}
for (const c of ["recommended", "all", "correctness"]) entries.push([`config:bpmnlint/${c}`, imp(`bpmnlint/config/${c}`)]);

for (const [name, rel] of Object.entries(compat.rules)) {
  if (name.startsWith("bpmnlint/")) continue; // re-exported core rule, already cached as rule:bpmnlint/*
  entries.push([`rule:bpmnlint-plugin-camunda-compat/${name}`, imp(require.resolve(path.join(compatDir, rel)))]);
}
lines.push(`import compat from "bpmnlint-plugin-camunda-compat";`);

lines.push("export const lintCache: Record<string, unknown> = {");
for (const [k, v] of entries) lines.push(`  ${JSON.stringify(k)}: ${v},`);
for (const c of Object.keys(compat.configs)) lines.push(`  ${JSON.stringify(`config:bpmnlint-plugin-camunda-compat/${c}`)}: compat.configs[${JSON.stringify(c)}],`);
lines.push("};");
lines.push(`export const compatConfigNames: string[] = ${JSON.stringify(Object.keys(compat.configs))};`);
fs.writeFileSync(out, lines.join("\n") + "\n");
console.error(`wrote ${path.relative(root, out)} (${entries.length} rules/configs)`);
